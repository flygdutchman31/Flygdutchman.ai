// Copies compiled ABIs into the web app so the frontend always matches the contracts.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const out = new URL("../../web/src/abi/", import.meta.url);
mkdirSync(out, { recursive: true });

const contracts = [
  ["agentBountyBoardAbi", "AgentBountyBoard", "AgentBountyBoard.sol/AgentBountyBoard.json"],
  ["mockAgentIdAbi", "MockAgentID", "test/MockAgentID.sol/MockAgentID.json"],
];

for (const [exportName, file, artifact] of contracts) {
  const { abi } = JSON.parse(readFileSync(new URL(`../artifacts/contracts/${artifact}`, import.meta.url), "utf8"));
  const body = `// Generated by contracts/scripts/export-abi.mjs, do not edit.\nexport const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;\n`;
  writeFileSync(new URL(`${file}.ts`, out), body);
}
console.log("ABIs exported to web/src/abi");
